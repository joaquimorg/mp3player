"""Generates a TFT_eSPI smooth font (.vlw format) as a C header from a TTF.

Usage (Pillow needed):
  python tools/make_vlw.py <font.ttf> <pixel size> <symbol name> <out.h>

The fonts in src/fonts/ were made from Droid Sans (Apache License 2.0, as
shipped e.g. in Android Studio's jbr/lib/fonts/DroidSans.ttf):
  python tools/make_vlw.py DroidSans.ttf 15 kFontS src/fonts/font_s.h
  python tools/make_vlw.py DroidSans.ttf 19 kFontM src/fonts/font_m.h
  python tools/make_vlw.py DroidSans.ttf 30 kFontL src/fonts/font_l.h

Glyph set: printable ASCII, Latin-1 (all Portuguese accented letters, º ª « »
€ is not Latin-1 and is added separately) and a few typographic marks. Glyphs
missing from the TTF are skipped, so the firmware's '?' substitution
(TFT_eSPI::getUnicodeIndex) stays truthful.

VLW layout (all integers big-endian int32):
  header: glyphCount, version 11, size, 0, ascent, descent
  per glyph: unicode, height, width, xAdvance, dY (baseline->top, +up), dX, 0
  then the 8-bit alpha bitmaps in glyph order, then a name trailer.
The header ascent is the max dY over the set (not the "d" ascent) so accented
capitals (É, Ç, Ã...) stay inside the text box TFT_eSPI uses for positioning.
"""
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

CODEPOINTS = (list(range(0x21, 0x7F)) + list(range(0xA1, 0x100)) +
              [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC])


def render(font, cp):
    ch = chr(cp)
    size = font.size * 3
    img = Image.new("L", (size, size), 0)
    ox, oy = font.size, font.size * 2  # pen position (baseline)
    ImageDraw.Draw(img).text((ox, oy), ch, font=font, fill=255, anchor="ls")
    box = img.getbbox()
    adv = int(round(font.getlength(ch)))
    if box is None:
        return None
    x0, y0, x1, y1 = box
    bmp = img.crop(box).tobytes()
    return dict(cp=cp, w=x1 - x0, h=y1 - y0, adv=adv, dY=oy - y0, dX=x0 - ox, bmp=bmp)


def main():
    ttf, px, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    font = ImageFont.truetype(ttf, px)
    notdef = render(font, 0xE000)  # private use: renders the .notdef box
    glyphs = []
    for cp in CODEPOINTS:
        g = render(font, cp)
        if g is None:
            continue
        if notdef and g["bmp"] == notdef["bmp"] and g["w"] == notdef["w"]:
            continue  # not in the font
        glyphs.append(g)
    ascent = max(g["dY"] for g in glyphs)
    descent = max(g["h"] - g["dY"] for g in glyphs if g["cp"] < 0x7F)
    data = bytearray(struct.pack(">6i", len(glyphs), 11, px, 0, ascent, descent))
    for g in glyphs:
        data += struct.pack(">7i", g["cp"], g["h"], g["w"], g["adv"], g["dY"], g["dX"], 0)
    for g in glyphs:
        data += g["bmp"]
    fam = font.getname()[0].encode()
    data += bytes([len(fam)]) + fam + b"\0" + bytes([len(fam)]) + fam + b"\0" + b"\1"

    with open(out, "w", newline="\n") as f:
        f.write("#pragma once\n// Generated by tools/make_vlw.py from %s (%s, %d px, %d glyphs).\n"
                % (ttf.replace("\\", "/").split("/")[-1], font.getname()[0], px, len(glyphs)))
        f.write("// Droid Sans: Copyright Google; Apache License 2.0.\n")
        f.write("#include <pgmspace.h>\n#include <stdint.h>\n")
        f.write("static const uint8_t %s[] PROGMEM = {\n" % name)
        for i in range(0, len(data), 24):
            f.write("".join("0x%02X," % b for b in data[i:i + 24]) + "\n")
        f.write("};\n")
    print("%s: %d glyphs, %d bytes, ascent %d descent %d" % (out, len(glyphs), len(data), ascent, descent))


if __name__ == "__main__":
    main()
